function filterTableRealTime() {
    const input = document.getElementById("liveSearchInput").value.toLowerCase();
    const rows = document.querySelectorAll("#attendanceMainTable tbody tr.accordion-toggle");

    rows.forEach(row => {
        const text = row.innerText.toLowerCase();
        const isMatch = text.includes(input);
        row.style.display = isMatch ? "" : "none";
        
        const detailId = row.getAttribute('onclick').match(/'([^']+)'/)[1];
        const detailRow = document.getElementById(detailId);
        if (detailRow) {
             detailRow.style.display = "none";
             row.classList.remove('active');
        }
    });
}

function handlePrintDTR() {
    const userIdInput = document.getElementById('userId');
    const userId = userIdInput ? userIdInput.value : '<?= $_SESSION['user_id'] ?>';
    const startDate = document.getElementById('startDate').value;
    const endDate = document.getElementById('endDate').value;

    if (!userId) {
        openModal('selectionWarningModal');
        return;
    }

    const url = `attendance_reports.php?action=print_dtr&user_id=${userId}&start_date=${startDate}&end_date=${endDate}`;
    document.getElementById('dtrFrame').src = url;
    openModal('dtrPreviewModal');
}

function openAttendanceDetail(type, title) {
    document.getElementById('detailModalTitle').innerText = title;
    document.getElementById('detailModalBody').innerHTML = '<div style="padding: 50px; text-align: center;"><i class="fa-solid fa-spinner fa-spin fa-2x"></i><p>Fetching records...</p></div>';
    openModal('attendanceDetailModal');

    fetch(`api.php?action=get_attendance_summary&type=${type}`)
        .then(res => res.json())
        .then(data => {
            if (data.success) {
                let html = '<table class="directory-table"><thead><tr><th>Faculty ID</th><th>Name</th><th>Position</th><th>Time</th></tr></thead><tbody>';
                data.users.forEach(u => {
                    html += `<tr>
                        <td style="font-weight:700;">${u.faculty_id}</td>
                        <td style="font-weight:600;">${u.first_name} ${u.last_name}</td>
                        <td><span class="ud-badge completed">${u.role}</span></td>
                        <td>${u.display_time}</td>
                    </tr>`;
                });
                if(data.users.length === 0) html += '<tr><td colspan="4" style="text-align:center; padding:40px; color:#94a3b8;">No records found for today.</td></tr>';
                html += '</tbody></table>';
                document.getElementById('detailModalBody').innerHTML = html;
            } else {
                document.getElementById('detailModalBody').innerHTML = `<p style="color:red; text-align:center; padding:20px;">${data.message}</p>`;
            }
        })
        .catch(err => {
            document.getElementById('detailModalBody').innerHTML = '<p style="color:red; text-align:center; padding:20px;">Connection Error.</p>';
        });
}

function renderAttendanceTable(users) {
    let html = `
        <table class="directory-table">
            <thead>
                <tr>
                    <th>Faculty ID</th>
                    <th>Name</th>
                    <th>Position</th>
                    <th>Time</th>
                </tr>
            </thead>
            <tbody>`;

    if (users.length === 0) {
        html += '<tr><td colspan="4" style="text-align:center; padding:40px; color:#94a3b8;">No records found for today.</td></tr>';
    } else {
        users.forEach(u => {
            let displayTime = u.timestamp ? new Date(u.timestamp).toLocaleTimeString([], {hour: '2-digit', minute:'2-digit'}) : '---';
            html += `
                <tr>
                    <td style="font-weight:700;">${u.faculty_id}</td>
                    <td style="font-weight:600;">${u.first_name} ${u.last_name}</td>
                    <td><span class="ud-badge completed">${u.role}</span></td>
                    <td>${displayTime}</td>
                </tr>`;
        });
    }
    html += '</tbody></table>';
    document.getElementById('detailModalBody').innerHTML = html;
}

