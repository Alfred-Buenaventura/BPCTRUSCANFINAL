function handleAjaxSubmit() {
    const form = document.getElementById('attendanceFeedbackForm');
    const btn = document.getElementById('submitReportBtn');
    
    if (!form.checkValidity()) {
        form.reportValidity();
        return;
    }

    btn.disabled = true;
    btn.innerHTML = '<i class="fa-solid fa-spinner fa-spin"></i> Sending...';

    const formData = new FormData(form);

    fetch('attendance_reports.php', {
        method: 'POST',
        body: formData
    })
    .then(response => {

        closeFeedbackModal();

        showStatusPopup("Report Submitted", "Your discrepancy report has been sent to the IT Department. Please wait for the official review.", "success");
    })
    .catch(error => {
        alert("Connection error. Please try again.");
    })
    .finally(() => {
        btn.disabled = false;
        btn.innerHTML = '<i class="fa-solid fa-paper-plane"></i> Submit Report';
    });
}

function showStatusPopup(title, message, type) {
    const modal = document.getElementById('statusPopupModal');
    const titleEl = modal.querySelector('h3');
    const messageEl = document.getElementById('statusModalMessage') || modal.querySelector('p');
    const iconContainer = modal.querySelector('.status-icon-circle');
    const icon = iconContainer.querySelector('i');

    titleEl.textContent = title;
    messageEl.textContent = message;

    if (type === 'success') {
        modal.querySelector('.modal-content').style.borderTop = "8px solid #10b981";
        iconContainer.style.background = "#ecfdf5";
        iconContainer.style.color = "#10b981";
        icon.className = "fa-solid fa-circle-check";
    } else {
        modal.querySelector('.modal-content').style.borderTop = "8px solid #ef4444";
        iconContainer.style.background = "#fef2f2";
        iconContainer.style.color = "#ef4444";
        icon.className = "fa-solid fa-circle-xmark";
    }

    modal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
}
